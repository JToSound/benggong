def test_basemap_coords_metadata_exists():
    """Coords metadata file must exist alongside the basemap."""
    if not COORDS_PATH.exists():
        pytest.skip(f"missing {COORDS_PATH}")
    with COORDS_PATH.open(encoding="utf-8") as f:
        coords = json.load(f)
    assert "bbox" in coords
    bbox = coords["bbox"]
    # All four required fields
    for key in ("lon_min", "lon_max", "lat_min", "lat_max"):
        assert key in bbox, f"missing bbox.{key}"
    # Sanity: Hong Kong is roughly 113.85-114.45 lon, 22.18-22.55 lat
    assert 113.0 < bbox["lon_min"] < 114.0
    assert 114.0 < bbox["lon_max"] < 115.0
    assert 22.0 < bbox["lat_min"] < 22.5
    assert 22.3 < bbox["lat_max"] < 23.0
    # size_px must match the actual image
    assert "size_px" in coords
    assert coords["size_px"] in (1024, 2048, 4096)


