def test_lonlat_projection_roundtrip():
    """Test the projection math: bbox corners should map to viewbox corners."""
    from PIL import Image  # noqa: F401  (force load to test env)
    with COORDS_PATH.open(encoding="utf-8") as f:
        coords = json.load(f)
    bbox = coords["bbox"]
    # Image-y axis is inverted relative to latitude (y points down on screen
    # but lat points up geographically). So (lon_min, lat_max) maps to
    # viewbox top-left (113.85, 22.18), and (lon_max, lat_min) to bottom-right
    # (113.85+0.60, 22.18+0.37).
    def project(lon, lat):
        fx = (lon - bbox["lon_min"]) / (bbox["lon_max"] - bbox["lon_min"])
        fy = (bbox["lat_max"] - lat) / (bbox["lat_max"] - bbox["lat_min"])
        return 113.85 + fx * 0.60, 22.18 + fy * 0.37
    # Top-left
    x, y = project(bbox["lon_min"], bbox["lat_max"])
    assert abs(x - 113.85) < 1e-9
    assert abs(y - 22.18) < 1e-9
    # Bottom-right
    x, y = project(bbox["lon_max"], bbox["lat_min"])
    assert abs(x - 114.45) < 1e-9
    assert abs(y - 22.55) < 1e-9
    # Midpoint
    x, y = project(
        (bbox["lon_min"] + bbox["lon_max"]) / 2,
        (bbox["lat_min"] + bbox["lat_max"]) / 2,
    )
    assert abs(x - 114.15) < 1e-9
    assert abs(y - 22.365) < 1e-9


